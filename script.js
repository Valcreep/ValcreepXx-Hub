/* ==================== 5. AMBIENT SPACE MUSIC SYNTH (WEB AUDIO API) ==================== */
let audioCtx = null;
let spaceGain = null;
let isSpaceAudioEnabled = true;
let spaceNodes = [];

function startSpaceAudio() {
  if (!isSpaceAudioEnabled) return;
  if (!audioCtx) {
    audioCtx = new (window.AudioContext || window.webkitAudioContext)();
  }
  if (audioCtx.state === "suspended") audioCtx.resume();
  if (spaceNodes.length > 0) return;

  spaceGain = audioCtx.createGain();
  spaceGain.gain.setValueAtTime(0.001, audioCtx.currentTime);
  spaceGain.gain.exponentialRampToValueAtTime(0.14, audioCtx.currentTime + 2.5);
  spaceGain.connect(audioCtx.destination);

  const freqs = [55, 82.41, 110, 164.81]; // Deep cosmic A-minor drone
  freqs.forEach((f, idx) => {
    const osc = audioCtx.createOscillator();
    const filter = audioCtx.createBiquadFilter();
    osc.type = idx % 2 === 0 ? "sine" : "triangle";
    osc.frequency.value = f;

    filter.type = "lowpass";
    filter.frequency.value = 320;

    osc.connect(filter);
    filter.connect(spaceGain);
    osc.start();
    spaceNodes.push(osc);
  });
}

function stopSpaceAudio() {
  if (spaceNodes.length > 0) {
    spaceNodes.forEach(osc => {
      try { osc.stop(); } catch (_) {}
    });
    spaceNodes = [];
  }
}

document.getElementById("btn-space-audio").addEventListener("click", (e) => {
  isSpaceAudioEnabled = !isSpaceAudioEnabled;
  const btn = e.currentTarget;
  if (isSpaceAudioEnabled) {
    btn.textContent = "🔊 SPACE SYNTH: ON";
    btn.classList.add("active-audio");
    startSpaceAudio();
  } else {
    btn.textContent = "🔇 SPACE SYNTH: OFF";
    btn.classList.remove("active-audio");
    stopSpaceAudio();
  }
});

